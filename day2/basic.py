# (%) use for modulus
print("\nModulus of two numbers")
num9 = int(input("Enter first number: "))
num10 = int(input("Enter second number: "))
mod = num9 % num10
print("Modulus is:", mod)

# (//) use for floor division
print("\nFloor Division of two numbers")
num11 = int(input("Enter first number: "))
num12 = int(input("Enter second number: "))
floordiv = num11 // num12
print("Floor Division is:", floordiv)

# (**) use for exponentiation
print("\nExponentiation of two numbers")
num13 = int(input("Enter first number: "))
num14 = int(input("Enter second number: "))
exp = num13 ** num14
print("Exponentiation is:", exp)
